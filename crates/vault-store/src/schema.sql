CREATE TABLE settings(key TEXT PRIMARY KEY NOT NULL, value TEXT NOT NULL);
CREATE TABLE vaults(id BLOB PRIMARY KEY NOT NULL CHECK(length(id)=16), operation BLOB NOT NULL CHECK(length(operation)=16), expires INTEGER NOT NULL, header TEXT NOT NULL);
CREATE TABLE credentials(id BLOB PRIMARY KEY NOT NULL, value TEXT NOT NULL);
CREATE TABLE receipts(operation BLOB PRIMARY KEY NOT NULL, digest BLOB NOT NULL, result TEXT NOT NULL, expires INTEGER NOT NULL);
